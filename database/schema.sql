-- SkillSync relational schema (PostgreSQL)
-- Run: psql "$DATABASE_URL" -f database/schema.sql
BEGIN;
CREATE TABLE IF NOT EXISTS student (
  student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  department VARCHAR(100) NOT NULL,
  year SMALLINT NOT NULL CHECK (year BETWEEN 1 AND 6),
  experience_level VARCHAR(30) NOT NULL CHECK (experience_level IN ('beginner','intermediate','advanced'))
);
CREATE TABLE IF NOT EXISTS skill (
  skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_name VARCHAR(100) NOT NULL UNIQUE,
  category VARCHAR(80) NOT NULL
);
CREATE TABLE IF NOT EXISTS student_skill (
  student_id BIGINT NOT NULL REFERENCES student(student_id) ON DELETE CASCADE,
  skill_id BIGINT NOT NULL REFERENCES skill(skill_id) ON DELETE CASCADE,
  proficiency VARCHAR(30) NOT NULL CHECK (proficiency IN ('beginner','intermediate','advanced','expert')),
  years_experience NUMERIC(4,1) NOT NULL DEFAULT 0 CHECK (years_experience >= 0),
  PRIMARY KEY (student_id, skill_id)
);
CREATE TABLE IF NOT EXISTS project (
  project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  description TEXT NOT NULL,
  owner_id BIGINT NOT NULL REFERENCES student(student_id) ON DELETE RESTRICT,
  status VARCHAR(30) NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','completed','archived')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS project_skill (
  project_id BIGINT NOT NULL REFERENCES project(project_id) ON DELETE CASCADE,
  skill_id BIGINT NOT NULL REFERENCES skill(skill_id) ON DELETE CASCADE,
  required_level VARCHAR(30) NOT NULL CHECK (required_level IN ('beginner','intermediate','advanced','expert')),
  PRIMARY KEY (project_id, skill_id)
);
CREATE TABLE IF NOT EXISTS application (
  application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES project(project_id) ON DELETE CASCADE,
  student_id BIGINT NOT NULL REFERENCES student(student_id) ON DELETE CASCADE,
  status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','withdrawn')),
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_application_project_student UNIQUE(project_id,student_id)
);
CREATE TABLE IF NOT EXISTS team (
  team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL UNIQUE REFERENCES project(project_id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS team_member (
  team_id BIGINT NOT NULL REFERENCES team(team_id) ON DELETE CASCADE,
  student_id BIGINT NOT NULL REFERENCES student(student_id) ON DELETE CASCADE,
  role VARCHAR(50) NOT NULL,
  PRIMARY KEY (team_id,student_id)
);
-- Indexes for joins, filtering, and recent activity
CREATE INDEX IF NOT EXISTS idx_student_department_year ON student(department,year);
CREATE INDEX IF NOT EXISTS idx_project_status_created ON project(status,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_application_student_status ON application(student_id,status);
CREATE INDEX IF NOT EXISTS idx_application_project_status ON application(project_id,status);
CREATE INDEX IF NOT EXISTS idx_student_skill_skill ON student_skill(skill_id,proficiency);
CREATE INDEX IF NOT EXISTS idx_project_description_fts ON project USING GIN(to_tsvector('english',description));
-- View: project demand and application counts
CREATE OR REPLACE VIEW project_summary AS
SELECT p.project_id,p.title,p.status,s.name AS owner_name,COUNT(DISTINCT ps.skill_id) AS required_skill_count,
       COUNT(DISTINCT a.application_id) AS application_count
FROM project p JOIN student s ON s.student_id=p.owner_id
LEFT JOIN project_skill ps ON ps.project_id=p.project_id
LEFT JOIN application a ON a.project_id=p.project_id
GROUP BY p.project_id,p.title,p.status,s.name;
-- Trigger function maintains a consistent modified status when a project receives first accepted application.
CREATE OR REPLACE FUNCTION set_project_in_progress() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status='accepted' AND OLD.status IS DISTINCT FROM NEW.status THEN
    UPDATE project SET status='in_progress' WHERE project_id=NEW.project_id AND status='open';
  END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_application_accept ON application;
CREATE TRIGGER trg_application_accept AFTER UPDATE OF status ON application
FOR EACH ROW EXECUTE FUNCTION set_project_in_progress();
COMMIT;
